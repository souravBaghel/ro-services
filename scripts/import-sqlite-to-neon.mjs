import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { neon } from "@neondatabase/serverless";

const envFile = resolve(".env");
if (existsSync(envFile)) process.loadEnvFile(envFile);

if (!process.env.DATABASE_URL) {
  throw new Error("Set DATABASE_URL to your Neon connection string before importing.");
}

const databasePath = resolve(process.env.DB_PATH || "data/bookings.sqlite");
if (!existsSync(databasePath)) {
  throw new Error(`SQLite database not found: ${databasePath}`);
}

const localDatabase = new DatabaseSync(databasePath);
const sql = neon(process.env.DATABASE_URL);
let imported = 0;
let skipped = 0;

try {
  await sql`
    CREATE TABLE IF NOT EXISTS bookings (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      phone TEXT NOT NULL,
      service TEXT NOT NULL,
      address TEXT NOT NULL,
      preferred_date DATE,
      issue TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      source_sqlite_id BIGINT UNIQUE
    )
  `;
  await sql`
    CREATE TABLE IF NOT EXISTS admin_login_attempts (
      ip TEXT PRIMARY KEY,
      attempts INTEGER NOT NULL,
      window_started_at TIMESTAMPTZ NOT NULL
    )
  `;

  const rows = localDatabase.prepare(`
    SELECT id, name, phone, service, address, preferred_date, issue, created_at
    FROM bookings
    ORDER BY id
  `).all();

  for (const row of rows) {
    const inserted = await sql`
      INSERT INTO bookings (
        source_sqlite_id,
        name,
        phone,
        service,
        address,
        preferred_date,
        issue,
        created_at
      )
      VALUES (
        ${row.id},
        ${row.name},
        ${row.phone},
        ${row.service},
        ${row.address},
        ${row.preferred_date}::date,
        ${row.issue},
        (CAST(${row.created_at} AS TIMESTAMP) AT TIME ZONE 'UTC')
      )
      ON CONFLICT (source_sqlite_id) DO NOTHING
      RETURNING id
    `;
    if (inserted.length) imported += 1;
    else skipped += 1;
  }

  console.log(`SQLite import complete: ${imported} imported, ${skipped} already present.`);
} finally {
  localDatabase.close();
}
